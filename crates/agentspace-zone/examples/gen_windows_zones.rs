//! Generates `src/cldr_windows_zones.rs` from CLDR's `windowsZones.xml` (docs/operator.md, The
//! time zone, step 1).
//!
//! RFC 2119 keywords in this comment, and the capitals are load-bearing.
//!
//! This is a developer tool. Cargo builds it with `--all-targets`, but nothing runs it at build
//! or test time, and it fetches nothing: the caller downloads the file and passes its path.
//! The file is data, and this program only reads it.
//!
//! ```text
//! cargo run -p agentspace-zone --example gen_windows_zones -- \
//!     <windowsZones.xml> <release> <date> <tag commit SHA> <SHA-256 of the file> \
//!     > crates/agentspace-zone/src/cldr_windows_zones.rs
//! ```
//!
//! The output holds every `<mapZone other=".." territory="001" type=".."/>` row, sorted by
//! Windows ID bytewise, which is the order the lookup's binary search needs. The tool stops with
//! a message when a row has no `other` or no `type`, when a `type` is not one plain name (it
//! MUST be for territory `001`), when an ID repeats, or when no row is found.

use std::process::ExitCode;

/// The value of attribute `name` in one tag's text, or `None` when it is absent.
fn attr<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let key = format!(" {name}=\"");
    let start = tag.find(&key)? + key.len();
    let len = tag[start..].find('"')?;
    Some(&tag[start..start + len])
}

fn run(args: &[String]) -> Result<String, String> {
    let [path, release, date, commit, sha256] = args else {
        return Err(
            "usage: gen_windows_zones <windowsZones.xml> <release> <date> <tag commit SHA> <SHA-256>"
                .into(),
        );
    };
    let xml = std::fs::read_to_string(path).map_err(|e| format!("cannot read {path}: {e}"))?;
    let mut rows: Vec<(String, String)> = Vec::new();
    for tag in xml.split('<').filter(|t| t.starts_with("mapZone ")) {
        if attr(tag, "territory") != Some("001") {
            continue;
        }
        let other = attr(tag, "other").ok_or_else(|| format!("no `other` in <{tag}"))?;
        let name = attr(tag, "type").ok_or_else(|| format!("no `type` in <{tag}"))?;
        if name.is_empty() || name.contains(|c: char| c.is_whitespace() || c == '\\') {
            return Err(format!("`type` is not a single plain name in <{tag}"));
        }
        if other.is_empty() || other.contains('\\') {
            return Err(format!("`other` is not plain in <{tag}"));
        }
        rows.push((other.to_owned(), name.to_owned()));
    }
    if rows.is_empty() {
        return Err("no territory=\"001\" rows found".into());
    }
    rows.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    if let Some(pair) = rows.windows(2).find(|p| p[0].0 == p[1].0) {
        return Err(format!("the ID {:?} repeats for territory 001", pair[0].0));
    }
    let mut out = format!(
        "// @generated by `cargo run -p agentspace-zone --example gen_windows_zones`; do not edit by hand.\n\
         //\n\
         // Source: CLDR {release}, published {date}\n\
         //   (github.com/unicode-org/cldr, tag `{release}`, commit {commit}),\n\
         //   file common/supplemental/windowsZones.xml, SHA-256 {sha256}.\n\
         // Rows: every `<mapZone other=\"..\" territory=\"001\" type=\"..\"/>` of that file,\n\
         //   sorted by Windows ID, bytewise.\n\
         // A new CLDR release is taken by regenerating this file in a story of its own\n\
         //   (docs/operator.md, The time zone, step 1).\n\
         \n\
         /// The CLDR release the table comes from.\n\
         pub const CLDR_RELEASE: &str = \"{release}\";\n\
         \n\
         /// The date that release was published.\n\
         pub const CLDR_RELEASE_DATE: &str = \"{date}\";\n\
         \n\
         /// CLDR's Windows ID to IANA name rows for territory `001`, sorted by Windows ID, bytewise.\n\
         pub(crate) const WINDOWS_ZONES: &[(&str, &str)] = &[\n"
    );
    for (other, name) in &rows {
        out.push_str(&format!("    (\"{other}\", \"{name}\"),\n"));
    }
    out.push_str("];\n");
    Ok(out)
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match run(&args) {
        Ok(text) => {
            print!("{text}");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("{message}");
            ExitCode::FAILURE
        }
    }
}
