//! The laptop's time zone as an IANA name, and the zone check (docs/operator.md, The time zone; D42).
//!
//! RFC 2119 keywords in this crate's comments, and the capitals are load-bearing.
//!
//! The one entry point is [`zone`]. It works out the zone the token push sends, in the order
//! the spec gives:
//!
//! 1. The override (`AGENTSPACE_TIMEZONE`, passed in by the caller) replaces the laptop's zone
//!    when it is set and not empty. Otherwise the laptop's Windows zone ID is converted with
//!    CLDR's mapping for territory `001` ([`windows_to_iana`]).
//! 2. Seven legacy names are mapped to their current ones ([`map_legacy`]).
//! 3. The zone MUST pass the zone check ([`is_valid_zone`]). One that does not, or no zone at all,
//!    is the empty zone, which this crate gives as `None`.
//!
//! The crate reads no environment variable and no file, writes to no stream, and never panics on
//! bad input. Reading the laptop's own Windows zone is not its job.

/// The seven legacy names and their current ones (operator.md, The time zone, step 2).
/// Names are matched case-sensitively.
pub const LEGACY_NAMES: [(&str, &str); 7] = [
    ("Asia/Calcutta", "Asia/Kolkata"),
    ("Asia/Katmandu", "Asia/Kathmandu"),
    ("Asia/Rangoon", "Asia/Yangon"),
    ("Europe/Kiev", "Europe/Kyiv"),
    ("America/Buenos_Aires", "America/Argentina/Buenos_Aires"),
    ("America/Godthab", "America/Nuuk"),
    ("America/Indianapolis", "America/Indiana/Indianapolis"),
];

// Step 1's table: the `territory="001"` rows of CLDR's `windowsZones.xml`, generated by
// `examples/gen_windows_zones.rs` and sorted by Windows ID, bytewise, so a lookup can bisect.
// The file's header names the CLDR release it comes from; a test keeps the rows sorted.
mod cldr_windows_zones;

use cldr_windows_zones::WINDOWS_ZONES;
pub use cldr_windows_zones::{CLDR_RELEASE, CLDR_RELEASE_DATE};

/// Converts a Windows zone ID to the IANA name CLDR gives for territory `001`, or `None` when
/// the ID is not known. The name is as CLDR gives it, so it MAY be a legacy one: [`zone`] maps
/// those afterwards.
///
/// The ID MUST be matched case-sensitively and whole, with no trimming, as ICU does (architect,
/// 2026-11-19, for E0.06-T01-S05).
pub fn windows_to_iana(windows_id: &str) -> Option<&'static str> {
    WINDOWS_ZONES
        .binary_search_by(|(id, _)| id.as_bytes().cmp(windows_id.as_bytes()))
        .ok()
        .map(|i| WINDOWS_ZONES[i].1)
}

/// Maps one of the seven legacy names to its current one, and gives every other name back as it
/// is. The match is case-sensitive.
pub fn map_legacy(name: &str) -> &str {
    LEGACY_NAMES
        .iter()
        .find(|(legacy, _)| *legacy == name)
        .map_or(name, |(_, current)| current)
}

/// The zone check of step 3: whether `name` matches
/// `^[A-Za-z0-9_+][A-Za-z0-9_+-]*(/[A-Za-z0-9_+-]+)*\z`, case-sensitively, where the letters are
/// the ASCII letters alone.
///
/// A leading `-` fails, because the box's zone tool would read it as an option. A trailing
/// newline fails, because `\z` is the end of the string and not the end before a newline. A
/// name that holds a quote, a space, a character a shell treats as syntax, or any non-ASCII
/// character fails.
pub fn is_valid_zone(name: &str) -> bool {
    fn plain(b: u8) -> bool {
        b.is_ascii_alphanumeric() || b == b'_' || b == b'+'
    }
    fn inner(b: u8) -> bool {
        plain(b) || b == b'-'
    }
    let mut segments = name.split('/');
    // The first segment: one plain character, then any inner ones.
    let Some(first) = segments.next() else {
        return false;
    };
    match first.as_bytes().split_first() {
        Some((head, tail)) if plain(*head) && tail.iter().copied().all(inner) => {}
        _ => return false,
    }
    // Every later segment is one or more inner characters, so it cannot be empty.
    segments.all(|s| !s.is_empty() && s.bytes().all(inner))
}

/// The zone check, giving the name back when it passes and `None` (the empty zone) when it
/// fails.
pub fn check_zone(name: &str) -> Option<&str> {
    is_valid_zone(name).then_some(name)
}

/// The zone the token push sends, as an IANA name, or `None` for the empty zone.
///
/// - `windows_id` is the Windows ID of the zone the laptop is set to, as the caller read it, or
///   `None` when it could not.
/// - `override_value` is the value of `AGENTSPACE_TIMEZONE`, or `None` when it is unset. When it
///   is set and not empty, it takes the place of step 1's result and `windows_id` is not used.
///   An empty override counts as unset. A value that is only whitespace is not empty, so it is
///   used, and it fails the check.
///
/// Whichever of the two supplies the name, the legacy names are mapped and the zone check
/// applies. A Windows ID that is not known, or a name that fails the check, gives `None`.
pub fn zone(windows_id: Option<&str>, override_value: Option<&str>) -> Option<String> {
    let converted: &str = match override_value {
        Some(value) if !value.is_empty() => value,
        _ => windows_to_iana(windows_id?)?,
    };
    check_zone(map_legacy(converted)).map(str::to_owned)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        for pair in WINDOWS_ZONES.windows(2) {
            assert!(pair[0].0.as_bytes() < pair[1].0.as_bytes(), "{pair:?}");
        }
    }

    /// The table is CLDR release-49's 142 `territory="001"` rows, and says which release it is.
    /// A regenerated table from another release MUST change this test with it.
    #[test]
    fn table_is_release_49s_142_rows() {
        assert_eq!(WINDOWS_ZONES.len(), 142);
        assert_eq!(CLDR_RELEASE, "release-49");
        assert_eq!(CLDR_RELEASE_DATE, "2026-10-21");
    }

    #[test]
    fn every_table_name_passes_the_check_once_mapped() {
        for (id, name) in WINDOWS_ZONES {
            assert!(is_valid_zone(name), "{id} -> {name}");
            assert!(is_valid_zone(map_legacy(name)), "{id} -> {name}");
        }
    }
}
